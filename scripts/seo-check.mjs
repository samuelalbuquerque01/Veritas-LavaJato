import assert from 'node:assert/strict';
import { siteUrl } from '../src/data/business.ts';

const base = process.env.VERITAS_TEST_URL || 'http://127.0.0.1:3400';
const page = await fetch(base);
assert.equal(page.status, 200);
const html = await page.text();
const canonical = html.match(/<link[^>]*rel="canonical"[^>]*href="([^"]+)"/);
assert.ok(canonical, 'The page must emit a canonical URL');
assert.equal(new URL(canonical[1]).href, `${siteUrl}/`);
const openGraphUrl = html.match(/property="og:url" content="([^"]+)"/);
assert.ok(openGraphUrl);
assert.equal(new URL(openGraphUrl[1]).href, `${siteUrl}/`);
assert.match(html, /property="og:image" content="https:\/\/veritaslavajato\.com\.br\/opengraph-image\.jpg/);
assert.ok(!html.includes('http://localhost:3000'));
const script = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
assert.ok(script, 'Local business JSON-LD must render in the page HTML');
const schema = JSON.parse(script[1]);
assert.equal(schema['@type'], 'AutoWash');
assert.equal(schema.url, `${siteUrl}/`);
assert.equal(schema.telephone, '+5585992510180');
assert.equal(schema.openingHoursSpecification.length, 2);
const robots = await fetch(`${base}/robots.txt`);
assert.equal(robots.status, 200);
const robotsText = await robots.text();
assert.ok(robotsText.includes(`Sitemap: ${siteUrl}/sitemap.xml`));
assert.ok(robotsText.includes('Allow: /'));
const sitemap = await fetch(`${base}/sitemap.xml`);
assert.equal(sitemap.status, 200);
assert.ok((await sitemap.text()).includes(`<loc>${siteUrl}/</loc>`));
console.log('SEO verified: canonical, Open Graph, AutoWash JSON-LD, robots.txt and sitemap.xml.');
